#!/usr/bin/env bash
# Requirement traceability gate and matrix generator (ADR-0004).
#   scripts/spec-check.sh            -> exit 1 on any gate failure
#   scripts/spec-check.sh --matrix   -> also (re)write specs/traceability.md
# Same rules as tests/spec_traceability.rs; this script additionally renders the matrix.
set -euo pipefail
cd "$(dirname "$0")/.."
python3 - "$@" <<'PY'
import os, re, sys, glob, datetime, collections

ROOT = os.getcwd()
ID_RE = re.compile(r'^[A-Z]+-[A-Z]+-\d{3}$')
FN_RE = re.compile(r'^\s*(?:pub\s+)?(?:async\s+)?fn\s+([A-Za-z0-9_]+)')
REQ_RE = re.compile(r'REQ:\s*([A-Z]+-[A-Z]+-\d{3}(?:\s*,\s*[A-Z]+-[A-Z]+-\d{3})*)')

def parse_spec(path):
    status, title, reqs, planned = '', '', [], collections.defaultdict(list)
    for line in open(path, encoding='utf-8'):
        if line.startswith('# ') and not title:
            title = line[2:].strip()
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) >= 2 and cells[0] == 'Status':
            status = cells[1]
        if len(cells) >= 3 and ID_RE.match(cells[0]):
            if cells[1] in ('MUST', 'SHOULD', 'MAY'):
                reqs.append((cells[0], cells[1], cells[2]))
            else:
                m = re.match(r'`?fn ([A-Za-z0-9_]+)\(\)`?', cells[1])
                if m:
                    planned[cells[0]].append(m.group(1))
    return dict(file=os.path.basename(path), title=title, status=status, reqs=reqs, planned=planned)

def scan_code():
    fns, comments, fn_files = set(), set(), {}
    for pat in ('src/**/*.rs', 'tests/**/*.rs'):
        for f in glob.glob(pat, recursive=True):
            for line in open(f, encoding='utf-8'):
                m = FN_RE.match(line)
                if m:
                    fns.add(m.group(1)); fn_files.setdefault(m.group(1), os.path.relpath(f))
                m = REQ_RE.search(line)
                if m:
                    for tok in re.split(r'\s*,\s*', m.group(1)):
                        comments.add(tok)
    return fns, comments, fn_files

specs = [parse_spec(p) for p in sorted(glob.glob('specs/features/*.md'))]
fns, comments, fn_files = scan_code()
failures, matrix = [], []
seen = {}
for s in specs:
    if s['status'] not in ('Draft', 'Accepted', 'Implemented', 'Withdrawn'):
        failures.append(f"{s['file']}: unknown or missing status '{s['status']}'")
    if not s['reqs']:
        failures.append(f"{s['file']}: no requirement rows")
    for rid, level, text in s['reqs']:
        if rid in seen:
            failures.append(f"duplicate id {rid} in {seen[rid]} and {s['file']}")
        seen[rid] = s['file']
        prefix = rid.lower().replace('-', '_')
        refs = sorted({f for f in fns if prefix in f} | {n for n in s['planned'].get(rid, []) if n in fns})
        if rid in comments:
            refs.append('REQ comment')
        gated = s['status'] in ('Accepted', 'Implemented')
        if gated and level == 'MUST' and not refs:
            failures.append(f"{s['file']}: {rid} (MUST, {s['status']}) has no test reference")
        matrix.append((rid, level, s['status'], text, refs, s['file']))
defined = set(seen)
for c in sorted(comments - defined):
    failures.append(f"code references undefined requirement {c}")
for f in sorted(fns):
    p = f.split('_')
    if len(p) >= 3 and re.fullmatch(r'\d{3}', p[2]):
        cand = f"{p[0].upper()}-{p[1].upper()}-{p[2]}"
        if ID_RE.match(cand) and cand not in defined:
            failures.append(f"fn {f} looks like a requirement test but {cand} is undefined")

if '--matrix' in sys.argv:
    covered = sum(1 for m in matrix if m[4])
    lines = ['# Traceability matrix', '',
             f'Generated by `scripts/spec-check.sh --matrix` on {datetime.date.today().isoformat()}. Do not edit by hand.', '',
             f'Requirements: {len(matrix)}  ·  with tests: {covered}  ·  specs: {len(specs)}', '',
             '| Requirement | Level | Spec status | Tests | Spec |', '|---|---|---|---|---|']
    for rid, level, status, text, refs, file in matrix:
        tests = ', '.join(f'`{r}`' for r in refs) if refs else '—'
        lines.append(f'| {rid} | {level} | {status} | {tests} | [{file}](features/{file}) |')
    open('specs/traceability.md', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'wrote specs/traceability.md ({len(matrix)} requirements, {covered} with tests)')

if failures:
    print('spec-check: FAILED'); [print('  -', f) for f in failures]; sys.exit(1)
print(f'spec-check: OK ({len(specs)} specs, {len(matrix)} requirements)')
PY
